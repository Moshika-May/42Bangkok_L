int	size_count(char *str)
{
	unsigned int	i;
	unsigned int	j;

	i = 0;
	j = 0;
	while (str[i] != '\0')
	{
		if (str[i] >= '1' && str[i] <= '9' && str[i] != ' ')
			j++;
		i++;
	}
	return (j / 4);
}
